package io.github.tendo505.tandem.server

import com.zaxxer.hikari.HikariConfig
import com.zaxxer.hikari.HikariDataSource
import io.github.tendo505.tandem.core.Field
import io.github.tendo505.tandem.core.Op
import io.github.tendo505.tandem.core.SeqOp
import java.sql.Connection
import javax.sql.DataSource

/**
 * An append-only, per-list log of ops in PostgreSQL (or H2 for development).
 *
 * Correctness hinges on one detail: clients page through the log with
 * "give me everything after seq N". If two uploads to the same list ran
 * concurrently, seq 42 could commit after seq 43 was already read, and a
 * client that had moved past 43 would never see 42. Writers to a list
 * therefore take a row lock on that list first, so seq order equals commit
 * order within a list. Different lists don't block each other.
 */
class OpStore(
    private val db: DataSource,
    /** Test hook: runs inside the write transaction just before commit, to widen race windows. */
    private val beforeCommit: () -> Unit = {},
) {

    fun migrate() = db.connection.use { c ->
        c.createStatement().use { s ->
            s.execute("CREATE TABLE IF NOT EXISTS lists (id VARCHAR(64) PRIMARY KEY, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)")
            s.execute(
                """
                CREATE TABLE IF NOT EXISTS ops (
                    seq     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    list_id VARCHAR(64) NOT NULL REFERENCES lists (id),
                    op_id   VARCHAR(64) NOT NULL,
                    entity  VARCHAR(64) NOT NULL,
                    field   VARCHAR(16) NOT NULL,
                    field_value VARCHAR(256) NOT NULL,
                    CONSTRAINT ops_unique UNIQUE (list_id, op_id)
                )
                """,
            )
            s.execute("CREATE INDEX IF NOT EXISTS ops_list_seq ON ops (list_id, seq)")
        }
    }

    /** Store ops (duplicates ignored). Returns how many were new and the list's latest seq. */
    fun append(listId: String, ops: List<Op>): Pair<Int, Long> = transaction { c ->
        c.prepareStatement("INSERT INTO lists (id) VALUES (?) ON CONFLICT DO NOTHING").use { it.setString(1, listId); it.executeUpdate() }
        c.prepareStatement("SELECT id FROM lists WHERE id = ? FOR UPDATE").use { it.setString(1, listId); it.executeQuery().close() }

        var stored = 0
        c.prepareStatement("INSERT INTO ops (list_id, op_id, entity, field, field_value) VALUES (?, ?, ?, ?, ?) ON CONFLICT DO NOTHING").use { ps ->
            for (op in ops) {
                ps.setString(1, listId); ps.setString(2, op.hlc); ps.setString(3, op.entity)
                ps.setString(4, op.field.name); ps.setString(5, op.value)
                stored += ps.executeUpdate()
            }
        }
        beforeCommit()
        stored to latestSeq(c, listId)
    }

    /** Up to [limit] ops after [after], in seq order. */
    fun after(listId: String, after: Long, limit: Int): Pair<List<SeqOp>, Long> = db.connection.use { c ->
        val ops = c.prepareStatement("SELECT seq, op_id, entity, field, field_value FROM ops WHERE list_id = ? AND seq > ? ORDER BY seq LIMIT ?").use { ps ->
            ps.setString(1, listId); ps.setLong(2, after); ps.setInt(3, limit)
            ps.executeQuery().use { rs ->
                buildList {
                    while (rs.next()) {
                        add(SeqOp(rs.getLong("seq"), Op(listId, rs.getString("entity"), Field.valueOf(rs.getString("field")), rs.getString("field_value"), rs.getString("op_id"))))
                    }
                }
            }
        }
        ops to latestSeq(c, listId)
    }

    private fun latestSeq(c: Connection, listId: String): Long =
        c.prepareStatement("SELECT COALESCE(MAX(seq), 0) FROM ops WHERE list_id = ?").use { ps ->
            ps.setString(1, listId); ps.executeQuery().use { rs -> rs.next(); rs.getLong(1) }
        }

    private fun <T> transaction(block: (Connection) -> T): T = db.connection.use { c ->
        c.autoCommit = false
        try {
            block(c).also { c.commit() }
        } catch (e: Throwable) {
            c.rollback(); throw e
        }
    }

    companion object {
        /** In-memory H2 by default; DATABASE_URL (postgres://user:pass@host:port/db) for PostgreSQL. */
        fun dataSource(databaseUrl: String?): HikariDataSource {
            val config = HikariConfig()
            if (databaseUrl.isNullOrBlank()) {
                config.jdbcUrl = "jdbc:h2:mem:tandem;DB_CLOSE_DELAY=-1;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DEFAULT_NULL_ORDERING=HIGH"
            } else if (databaseUrl.startsWith("jdbc:")) {
                config.jdbcUrl = databaseUrl
            } else {
                val uri = java.net.URI(databaseUrl)
                val (user, pass) = (uri.userInfo ?: ":").split(":", limit = 2).let { it[0] to it.getOrElse(1) { "" } }
                config.jdbcUrl = "jdbc:postgresql://${uri.host}:${if (uri.port == -1) 5432 else uri.port}${uri.path}" + (uri.query?.let { "?$it" } ?: "")
                config.username = java.net.URLDecoder.decode(user, Charsets.UTF_8)
                config.password = java.net.URLDecoder.decode(pass, Charsets.UTF_8)
            }
            config.maximumPoolSize = 10
            return HikariDataSource(config)
        }
    }
}
